/// The level of a guide rule ID; `None` when the guide has no such rule.
pub fn guide_level(id: &str) -> Option<GuideLevel> {
    GUIDE_IDS.iter().find(|(i, _)| *i == id).map(|(_, l)| *l)
}

/// Whether `s` is written like a guide rule ID (`ABC-12`), whether or not the guide has it.
pub fn looks_like_guide_id(s: &str) -> bool {
    let b = s.as_bytes();
    b.len() >= 5 && b[..3].iter().all(u8::is_ascii_uppercase) && b[3] == b'-' && b[4..].iter().all(u8::is_ascii_digit)
}
