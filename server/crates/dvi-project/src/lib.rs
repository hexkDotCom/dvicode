        let log = "\"C:\\Program Files\\Questa\\win64\\vlog.exe\" -sv -Lf vendor_lib -dpiheader dpi.h \"+define+MSG=hello world\" +dvicode_init_from_simlog+compile.log -f lists/tb.f rtl/top.sv rtl/missing.sv\n";
