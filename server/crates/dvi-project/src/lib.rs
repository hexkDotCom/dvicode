    #[test]
    fn parses_directives() {
        let dir = std::env::temp_dir().join("dvicode_build_test");
        std::fs::create_dir_all(dir.join("inc")).unwrap();
        std::fs::write(dir.join("a.sv"), "module a; endmodule").unwrap();
        std::fs::write(dir.join("inc/b.f"), "../a.sv\n+define+FROM_F\n").unwrap();
        let text = "// comment\n+incdir+inc+$MYDIR\n+define+A=1+B+C=\"x y\"\n-f inc/b.f\n# hash comment\na.sv -top top_tb\n";
        let mut env = FxHashMap::default();
        env.insert("MYDIR".to_string(), dir.join("inc").display().to_string());
        let cfg = parse_build(&dir, &dir.join(".dvicode/default.build"), text, &env);
        assert_eq!(cfg.invocations.len(), 1);
        let inv = &cfg.invocations[0];
        assert_eq!(inv.files, vec![dir.join("a.sv")]);
        assert_eq!(inv.incdirs, vec![dir.join("inc")]);
        let names: Vec<_> = inv.defines.iter().map(|d| d.0.as_str()).collect();
        assert_eq!(names, vec!["A", "B", "C", "FROM_F"]);
        assert_eq!(inv.defines[2].1.as_deref(), Some("\"x y\""));
        assert_eq!(inv.tops, vec!["top_tb".to_string()]);
    }

