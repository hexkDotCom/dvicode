        assert_eq!(got, vec![("vcs".into(), vec![dir.join("a.sv")], vec!["A".into()]), ("vcs".into(), vec![dir.join("b.sv")], vec!["B".into()]), ("vcs".into(), vec![], vec!["LAST".into()])]);
