//! Project build configuration.
//!
//! Reads build files (`.dvicode/*.build`) and simulator `-f` argument files, and can
//! auto-configure a project when no
//! build file exists.

mod auto;
mod glob;
mod jinja;
mod progress;
mod simlog;

pub use auto::{auto_config, auto_config_with};
pub use progress::{Phase, Progress};

use rustc_hash::FxHashMap;
use std::path::{Path, PathBuf};

#[derive(Clone, Debug, Default)]
pub struct Invocation {
    /// `+dvicode_init+<mode>`; `default` when not given.
    pub mode: String,
    /// Top files in compile order.
    pub files: Vec<PathBuf>,
    pub incdirs: Vec<PathBuf>,
    /// `+define+` in order; `None` value for `+define+NAME`.
    pub defines: Vec<(String, Option<String>)>,
    pub undefines: Vec<String>,
    /// `-y` library directories.
    pub lib_dirs: Vec<PathBuf>,
    /// `-v` library files.
    pub lib_files: Vec<PathBuf>,
    pub libext: Vec<String>,
    pub tops: Vec<String>,
    /// `+dvicode_skip_compile+` patterns.
    pub skip: Vec<String>,
    /// The section was generated by auto-configuration.
    pub auto: bool,
    /// Other `+NAME=value` / `+NAME+value` arguments (simulation plusargs such as
    /// `+UVM_TESTNAME`), in order.
    pub plusargs: Vec<(String, Option<String>)>,
}

/// A problem in a build or argument file.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct BuildProblem {
    pub file: PathBuf,
    /// Zero-based line.
    pub line: u32,
    /// Byte range in the file of what is wrong; `None`: the whole line.
    pub range: Option<(u32, u32)>,
    pub message: String,
}

/// What [`inspect`] finds out about one build or argument file, for the editor.
#[derive(Clone, Debug, Default)]
pub struct Inspection {
    /// Problems in the file itself (those of the argument files it reads are left out).
    pub problems: Vec<BuildProblem>,
    /// What words mean: resolved paths, what wildcards match, values (Markdown), by byte range.
    pub notes: Vec<(u32, u32, String)>,
    /// Paths of existing files, by byte range.
    pub links: Vec<(u32, u32, PathBuf)>,
}

#[derive(Clone, Debug, Default)]
pub struct BuildConfig {
    pub root: PathBuf,
    pub build_file: Option<PathBuf>,
    pub invocations: Vec<Invocation>,
    /// Problems in the build file and the argument files it reads.
    pub problems: Vec<BuildProblem>,
    /// The argument files read, and how (to check one the way the build reads it).
    pub arg_files: Vec<ArgFile>,
}

/// An argument file a build reads, and what it is read with.
#[derive(Clone, Debug, Default)]
pub struct ArgFile {
    pub path: PathBuf,
    /// Where its relative paths start.
    pub base: PathBuf,
    /// The variables set when it is read (the settings' and the build file's).
    pub env: FxHashMap<String, String>,
    /// The `+dvicode_init` mode and compilation root at that point.
    pub mode: String,
    pub comp_root: PathBuf,
    /// The `+dvicode_switches+` its Jinja conditions are evaluated with.
    pub switches: Vec<String>,
    /// The `+dvicode_path_map+` mappings in effect.
    pub path_maps: Vec<(String, String)>,
}

impl BuildConfig {
    pub fn all_files(&self) -> impl Iterator<Item = &PathBuf> {
        self.invocations.iter().flat_map(|i| i.files.iter())
    }

    pub fn tops(&self) -> Vec<String> {
        self.invocations.iter().flat_map(|i| i.tops.iter().cloned()).collect()
    }

    /// Value of the last `+NAME=value` (or `+NAME+value`) plusarg.
    pub fn plusarg(&self, name: &str) -> Option<String> {
        self.invocations
            .iter()
            .flat_map(|i| i.plusargs.iter())
            .filter(|(n, _)| n == name)
            .last()
            .and_then(|(_, v)| v.clone())
    }

    /// The UVM test selected with `+UVM_TESTNAME`.
    pub fn uvm_testname(&self) -> Option<String> {
        self.plusarg("UVM_TESTNAME").filter(|t| !t.is_empty())
    }
}

/// The default build file of a project, if any.
pub fn find_build_file(root: &Path) -> Option<PathBuf> {
    Some(root.join(".dvicode/default.build")).filter(|p| p.is_file())
}

/// All build configurations of a project (`.dvicode/*.build`).
pub fn list_build_files(root: &Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    for dir in [".dvicode"] {
        if let Ok(rd) = std::fs::read_dir(root.join(dir)) {
            let mut v: Vec<PathBuf> = rd
                .filter_map(|e| e.ok().map(|e| e.path()))
                .filter(|p| p.extension().is_some_and(|e| e == "build"))
                .collect();
            v.sort();
            out.extend(v);
        }
    }
    out
}

/// Loads the configuration of a project: the given build file, the default one, or an
/// auto-configuration.
/// Setting value that asks for auto-configuration even when a default build file exists.
pub const AUTO: &str = "auto";

/// Auto-configuration, ignoring any build file.
pub fn load_auto(root: &Path, env: &FxHashMap<String, String>) -> BuildConfig {
    load_auto_with(root, env, &Progress::new())
}

/// [`load_auto`], reporting on (and cancelled through) `progress`.
pub fn load_auto_with(root: &Path, env: &FxHashMap<String, String>, progress: &Progress) -> BuildConfig {
    BuildConfig { root: root.to_path_buf(), build_file: None, invocations: vec![auto_config_with(root, env, progress)], ..Default::default() }
}

pub fn load(root: &Path, build_file: Option<&Path>, env: &FxHashMap<String, String>) -> BuildConfig {
    load_with(root, build_file, env, &Progress::new())
}

/// [`load`], reporting the auto-configuration on (and cancelled through) `progress`.
pub fn load_with(root: &Path, build_file: Option<&Path>, env: &FxHashMap<String, String>, progress: &Progress) -> BuildConfig {
    let bf = build_file.map(|p| p.to_path_buf()).or_else(|| find_build_file(root));
    match bf {
        Some(bf) => match std::fs::read_to_string(&bf) {
            Ok(text) => parse_build_with(root, &bf, &text, env, progress),
            Err(e) => {
                let mut cfg = parse_build_with(root, &bf, "", env, progress);
                cfg.problems.push(BuildProblem { file: bf.clone(), line: 0, range: None, message: format!("Cannot read the build file {}: {e}", bf.display()) });
                cfg
            }
        },
        None => BuildConfig {
            root: root.to_path_buf(),
            build_file: None,
            invocations: vec![auto_config_with(root, env, progress)],
            ..Default::default()
        },
    }
}

/// Parses build file text.
pub fn parse_build(root: &Path, build_file: &Path, text: &str, env: &FxHashMap<String, String>) -> BuildConfig {
    parse_build_with(root, build_file, text, env, &Progress::new())
}

/// [`parse_build`], scanning `+dvicode_init_auto` sections on (and cancelled through) `progress`.
pub fn parse_build_with(root: &Path, build_file: &Path, text: &str, env: &FxHashMap<String, String>, progress: &Progress) -> BuildConfig {
    let mut b = Builder::new(root, build_file, env, false);
    b.parse_text(build_file, text, root.to_path_buf());
    b.finish(progress)
}

/// Checks the text of a build file (`.dvicode/*.build`, relative paths from the project
/// folder `root`) or, given how a build reads it, of an argument file, for an editor: its
/// problems, what its words resolve to, and links to the files it names. Argument files it
/// reads are read from disk; `+dvicode_init_auto` sections are not scanned.
pub fn inspect(root: &Path, file: &Path, text: &str, env: &FxHashMap<String, String>, argument_file: Option<&ArgFile>) -> Inspection {
    let mut b = Builder::new(root, file, env, true);
    let base = match argument_file {
        Some(a) => {
            b.env = a.env.clone();
            b.comp_root = a.comp_root.clone();
            b.inv().mode = a.mode.clone();
            b.switches = a.switches.clone();
            b.path_maps = a.path_maps.clone();
            a.base.clone()
        }
        None => root.to_path_buf(),
    };
    b.parse_text(file, text, base);
    // The last invocation's UVM library, with its note. In an argument file that invocation
    // goes on after the file, where the build may still give the UVM location (invocations the
    // file ends itself are complete).
    b.partial = argument_file.is_some();
    b.apply_uvm();
    let (notes, links) = (std::mem::take(&mut b.notes), std::mem::take(&mut b.links));
    let cfg = b.finish(&Progress::new());
    let own = |f: &Path| f == file;
    Inspection {
        problems: cfg.problems.into_iter().filter(|p| own(&p.file)).collect(),
        notes: notes.into_iter().filter(|(f, ..)| own(f)).map(|(_, s, e, t)| (s, e, t)).collect(),
        links: links.into_iter().filter(|(f, ..)| own(f)).map(|(_, s, e, t)| (s, e, t)).collect(),
    }
}

struct Builder {
    cfg: BuildConfig,
    cur: Option<Invocation>,
    env: FxHashMap<String, String>,
    comp_root: PathBuf,
    /// Set by `+dvicode_compilation_root+` (the new base) and `+dvicode_init` (back to the
    /// file's own base) for the file being parsed.
    base_change: Option<Option<PathBuf>>,
    /// UVM requested in the current invocation.
    uvm: Option<UvmRequest>,
    depth: usize,
    /// The build file and the argument files being read, innermost last.
    reading: Vec<PathBuf>,
    /// Argument files read so far.
    files_read: usize,
    /// The word being read: byte range in its file, and its text there. Problems point at
    /// `span` (the word, its argument, or the part of a `+opt+a+b` word that is wrong).
    span: (u32, u32),
    word: (u32, String),
    /// Where [`Builder::focus`] looks for the next argument in `word`: after the option name
    /// and the arguments already pointed at.
    focus_at: usize,
    /// Reading an argument file on its own ([`inspect`]): what the rest of the build sets later
    /// (such as the UVM location) is unknown.
    partial: bool,
    /// For [`inspect`]: collect `notes` and `links` (file, byte range, ...); skip scanning for
    /// `+dvicode_init_auto`.
    inspecting: bool,
    notes: Vec<(PathBuf, u32, u32, String)>,
    links: Vec<(PathBuf, u32, u32, PathBuf)>,
    /// `+dvicode_switches+`: what Jinja conditions in argument files test.
    switches: Vec<String>,
    /// `+dvicode_path_map+FROM=TO`, longest FROM first: paths written on another machine.
    path_maps: Vec<(String, String)>,
}

