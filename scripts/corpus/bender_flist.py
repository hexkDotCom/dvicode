#!/usr/bin/env python3
"""Turn Bender.yml manifests (PULP) into a DVICode build file.

Packages are given in dependency order as NAME=DIR; each contributes its sources whose
`target` expression holds for the given targets, its include directories and defines.

    bender_flist.py --var CORPUS --pkg common_cells=CLONE --pkg axi=CLONE -o axi.build
"""

import argparse
import os
import re
import sys

import yaml


def holds(expr, targets):
    """Evaluates a Bender target expression: name, all(...), any(...), not(...), *."""
    expr = expr.strip()
    if expr == "*":
        return True
    m = re.match(r"^(all|any|not)\((.*)\)$", expr, re.S)
    if not m:
        return expr in targets
    op, body = m.groups()
    args, depth, cur = [], 0, ""
    for ch in body:
        if ch == "," and depth == 0:
            args.append(cur)
            cur = ""
            continue
        depth += ch == "("
        depth -= ch == ")"
        cur += ch
    if cur.strip():
        args.append(cur)
    vals = [holds(a, targets) for a in args]
    return all(vals) if op == "all" else any(vals) if op == "any" else not vals[0]


def collect(entries, targets, d, out, defines):
    for e in entries or []:
        if isinstance(e, str):
            out.append(os.path.normpath(os.path.join(d, e)))
            continue
        if "target" in e and not holds(e["target"], targets):
            continue
        for k, v in (e.get("defines") or {}).items():
            if isinstance(v, dict):
                if holds(v.get("target", "*"), targets):
                    defines.append(k)
            else:
                defines.append(k if v is None else f"{k}={v}")
        for i in e.get("include_dirs") or []:
            out.append(("incdir", os.path.normpath(os.path.join(d, i))))
        collect(e.get("files"), targets, d, out, defines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--pkg", action="append", required=True, help="NAME=DIR, dependencies first")
    ap.add_argument("--target", action="append", default=[], help="Bender target that is set")
    ap.add_argument("--base", required=True, help="directory that the variable names")
    ap.add_argument("--var", required=True, help="variable for --base in the build file, e.g. CORPUS")
    ap.add_argument("-o", "--output", required=True)
    a = ap.parse_args()
    base = os.path.realpath(a.base)

    incdirs, files, defines = [], [], []
    for spec in a.pkg:
        name, d = spec.split("=", 1)
        d = os.path.realpath(d)
        with open(os.path.join(d, "Bender.yml"), encoding="utf-8") as f:
            y = yaml.safe_load(f)
        for i in y.get("export_include_dirs") or []:
            incdirs.append(os.path.join(d, i))
        out = []
        collect(y.get("sources"), set(a.target), d, out, defines)
        incdirs += [p for k, p in (x for x in out if isinstance(x, tuple))]
        files += [x for x in out if not isinstance(x, tuple)]

    def rel(p):
        return f"${a.var}/{os.path.relpath(p, base)}"

    lines = [f"// Generated by scripts/corpus/bender_flist.py from the Bender.yml of {', '.join(s.split('=')[0] for s in a.pkg)}"]
    lines += [f"+define+{x}" for x in dict.fromkeys(defines)]
    lines += [f"+incdir+{rel(p)}" for p in dict.fromkeys(incdirs)]
    lines += [rel(p) for p in dict.fromkeys(files)]
    with open(a.output, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{a.output}: {len(files)} files", file=sys.stderr)


if __name__ == "__main__":
    main()
