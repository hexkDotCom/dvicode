#!/usr/bin/env python3
"""Turn the file list that FuseSoC generates for a core (as OpenTitan's dvsim runs it) into a
DVICode build file.

Runs `fusesoc --cores-root ROOT/hw run --no-export --target=sim --setup CORE` in a temporary
directory and converts the `.scr` file: paths in the clone are written relative to a variable
(`$CORPUS/opentitan/...`), and files that FuseSoC generators produced (register packages, CSR
assertions) become `// corpus-setup:` lines that run.sh turns into regtool calls.

    fusesoc_build.py --root CLONE --core lowrisc:dv:uart_sim:0.1 \
        --var CORPUS/opentitan --gen-var CORPUS/.gen/opentitan -o uart.build
"""

import argparse
import glob
import os
import subprocess
import sys
import tempfile

import yaml


def generated(path, var_gen, root):
    """(build file path, setup line) for a file in FuseSoC's generator cache."""
    d = os.path.dirname(path)
    inputs = glob.glob(os.path.join(d, "*_input.yml"))
    if not inputs:
        sys.exit(f"no generator input next to {path}")
    with open(inputs[0], encoding="utf-8") as f:
        y = yaml.safe_load(f)
    par = y.get("parameters") or {}
    base = os.path.basename(path)
    spec = par.get("ip_hjson") or par.get("spec")
    if not spec:
        sys.exit(f"unsupported generator for {path}: {par}")
    hjson = os.path.relpath(os.path.normpath(os.path.join(y["files_root"], spec)), root)
    name = par.get("name") or os.path.splitext(os.path.basename(hjson))[0]
    opt = "-s" if base.endswith("_ral_pkg.sv") else "-f"
    return f"${var_gen}/{name}/{base}", f"// corpus-setup: regtool {opt} {name} {hjson}"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", required=True, help="clone of the project")
    ap.add_argument("--core", required=True)
    ap.add_argument("--fusesoc", default="fusesoc")
    ap.add_argument("--flag", action="append", default=[], help="extra FuseSoC run option, e.g. --mapping=...")
    ap.add_argument("--var", required=True, help="how the build file names the clone, e.g. CORPUS/opentitan")
    ap.add_argument("--gen-var", required=True, help="how the build file names the generated-files directory")
    ap.add_argument("--uvm", action="store_true", help="start with -uvm")
    ap.add_argument("--define", action="append", default=[])
    ap.add_argument("--top", default="")
    ap.add_argument("-o", "--output", required=True)
    a = ap.parse_args()

    root = os.path.realpath(a.root)
    with tempfile.TemporaryDirectory() as tmp:
        work = os.path.join(tmp, "work")
        cmd = [a.fusesoc, "--cores-root", os.path.join(root, "hw"), "run", "--no-export", *a.flag,
               "--target=sim", f"--work-root={work}", "--setup", a.core]
        r = subprocess.run(cmd, cwd=tmp, capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit(f"{' '.join(cmd)} failed:\n{r.stdout}{r.stderr}")
        scr = glob.glob(os.path.join(work, "*.scr"))[0]
        with open(scr, encoding="utf-8") as f:
            entries = f.read().split()

        def rel(p):
            p = os.path.normpath(os.path.join(work, p))
            if p.startswith(work + os.sep):
                return generated(p, a.gen_var, root)
            q = os.path.relpath(p, root)
            if q.startswith(".."):
                sys.exit(f"path outside the clone: {p}")
            return f"${a.var}/{q}", None

        lines = [f"// Generated by scripts/corpus/gen-builds.sh: the FuseSoC file list of {a.core}",
                 "// (target sim, as dvsim runs it). Regenerate after changing the pinned commit."]
        body = []
        if a.uvm:
            body.append("-uvm")
        body += [f"+define+{d}" for d in a.define]
        for e in entries:
            if e.startswith("+incdir+"):
                body.append("+incdir+" + rel(e[len("+incdir+"):])[0])
            elif e.startswith("+define+") or e.startswith("-"):
                body.append(e)
            else:
                path, setup = rel(e)
                if setup:
                    lines.append(setup)
                body.append(path)
        if a.top:
            body.append(f"-top {a.top}")
    with open(a.output, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines + body) + "\n")
    n = sum(1 for b in body if not b.startswith(("+", "-")))
    print(f"{a.output}: {n} files", file=sys.stderr)


if __name__ == "__main__":
    main()
